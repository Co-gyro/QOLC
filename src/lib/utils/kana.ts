/** 住所フリガナ（全角カタカナ＋数字・ハイフン）の検証用正規表現 */
export const ADDRESS_KATAKANA_RE = /^[ァ-ヶー　 ・０-９0-9－―‐-]+$/;

/**
 * 全角カタカナを半角カナへ変換する（JCB申請書のカナ欄用）。
 * 対応表にない文字（既に半角のカナ・英数字等）はそのまま通す。
 * @param input 全角カタカナ文字列（例: "ユニバーサルデベロップメント"）
 * @returns 半角カナ文字列（例: "ﾕﾆﾊﾞｰｻﾙﾃﾞﾍﾞﾛｯﾌﾟﾒﾝﾄ"）
 */
export function toHalfWidthKana(input: string): string {
  let out = "";
  for (const ch of input) {
    out += KANA_MAP[ch] ?? ch;
  }
  return out;
}
